    def _require_auth(self):
        """Return True if the request may proceed; otherwise serve login."""
        if self._authed():
            return True
        u = urlparse(self.path)
        if u.path == "/login":
            return True  # handled by do_GET/do_POST below
        if u.path == "/logo":
            return True  # public brand asset; needed by headless PDF rendering
        self.send_response(302)
        self.send_header("Location", "/login")
        self.send_header("Content-Length", "0")
        self.end_headers()
        return False
    # ----------------------------------------------------------------------

    def _send(self, code, body, ctype="application/json"):
        if isinstance(body, (dict, list)):
            body = json.dumps(body).encode('utf-8')
        elif isinstance(body, str):
            body = body.encode('utf-8')
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _send_file(self, path, ctype, download_name=None):
        if not os.path.isfile(path):
            return self._send(404, {"error": "not found"})
        with open(path, 'rb') as f:
            body = f.read()
        self.send_response(200)
        self.send_header("Content-Type", ctype)
        if download_name:
            self.send_header("Content-Disposition", f'attachment; filename="{download_name}"')
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        u = urlparse(self.path)
        q = parse_qs(u.query)
        if u.path == "/login":
            return self._login_page()
        if not self._require_auth():
            return
        if u.path == "/" or u.path == "/index.html" or u.path == "/conveyor":
            return self._send(200, CONVEYOR_INTAKE_HTML, "text/html; charset=utf-8")
        if u.path == "/conveyor/quote":
            return self._conveyor_quote(q.get('id', [''])[0])
        if u.path == "/conveyor/download":
            self._conveyor_download(q.get('id', [''])[0])
            return
        if u.path == "/api/conveyor/defaults":
            return self._send(200, default_conveyor_quote())
        if u.path == "/api/conveyor/config":
            import firecrawl_extract
            return self._send(200, {"has_api_key": bool(firecrawl_extract.get_api_key())})
        if u.path == "/api/conveyor/jobs":
            return self._send(200, list_conveyor_jobs())
        if u.path == "/api/conveyor/job":
            jdir = safe_job_dir(q.get('id', [''])[0])
            if jdir is None:
                return self._send(400, {"error": "bad id"})
            jp = os.path.join(jdir, "conveyor.json")
            if os.path.isfile(jp):
                with open(jp, encoding='utf-8') as f:
                    data = json.load(f)
                data = refresh_conveyor_from_scrape(jdir, data)
                return self._send(200, data)
            return self._send(404, {"error": "not found"})
        if u.path == "/api/jobs":
            return self._send(200, list_jobs())
        if u.path == "/api/job":
            jdir = safe_job_dir(q.get('id', [''])[0])
            if jdir is None:
                return self._send(400, {"error": "bad id"})
            jp = os.path.join(jdir, "quote.json")
            if os.path.isfile(jp):
                with open(jp, encoding='utf-8') as f:
                    return self._send(200, json.load(f))
            return self._send(404, {"error": "not found"})
        if u.path == "/api/defaults":
            return self._send(200, default_quote())
        if u.path == "/download":
            jid = q.get('id', [''])[0]
            fmt = q.get('fmt', ['pdf'])[0]
            self._download(jid, fmt)
            return
        if u.path == "/logo":
            if os.path.isfile(LOGO_PATH):
                return self._send_file(LOGO_PATH, "image/png")
            return self._send(404, b"")
        return self._send(404, {"error": "not found"})

    def do_POST(self):
        u = urlparse(self.path)
        length = int(self.headers.get('Content-Length', 0))
        raw = self.rfile.read(length) if length else b'{}'

        if u.path == "/login":
            pw = raw.decode('utf-8', 'replace')
            # accept form-encoded or JSON
            if "=" in pw and not pw.strip().startswith("{"):
                from urllib.parse import parse_qsl
                pw = dict(parse_qsl(pw)).get("pw", "")
            else:
                try:
                    pw = json.loads(pw).get("pw", "")
                except Exception:
                    pw = ""
            if pw == self.APP_PASSWORD:
                self.send_response(303)
                self.send_header("Location", "/")
                self.send_header("Set-Cookie", self.AUTH_COOKIE + "; Path=/; HttpOnly; Max-Age=2592000")
                self.send_header("Content-Length", "0")
                self.end_headers()
            else:
                self._login_page("Wrong password — try again")
            return

        if not self._require_auth():
            return
        try:
            data = json.loads(raw.decode('utf-8'))
        except Exception:
            return self._send(400, {"error": "bad json"})

        if u.path == "/api/save":
            return self._save(data)
        if u.path == "/api/conveyor/save":
            return self._save_conveyor(data)
        if u.path == "/api/conveyor/extract":
            return self._conveyor_extract(data)
        if u.path == "/api/conveyor/render":
            return self._conveyor_render(data)
        if u.path == "/conveyor/screenshot":
            return self._conveyor_screenshot(data)
        if u.path == "/api/delete":
            jdir = safe_job_dir(data.get('id', ''))
            if jdir is None:
                return self._send(400, {"error": "bad id"})
            if os.path.isdir(jdir):
                import shutil
                shutil.rmtree(jdir)
                return self._send(200, {"ok": True})
            return self._send(404, {"error": "not found"})
        return self._send(404, {"error": "not found"})

    def _save(self, data):
        # Reuse the existing id only if it passes validation; otherwise mint a
        # fresh one. This stops a crafted _id from steering writes out of jobs/.
        jid = data.get('_id')
        if not jid or safe_job_dir(jid) is None:
            jid = new_job_id(data)
        data['_id'] = jid
        data['_saved_at'] = datetime.now().isoformat(timespec='seconds')
        jdir = os.path.join(JOBS_DIR, jid)
        os.makedirs(jdir, exist_ok=True)
        with open(os.path.join(jdir, "quote.json"), 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=2)
        return self._send(200, {"ok": True, "id": jid})

    def _download(self, jid, fmt):
        jdir = safe_job_dir(jid)
        if jdir is None:
            return self._send(400, {"error": "bad id"})
        jp = os.path.join(jdir, "quote.json")
        if not os.path.isfile(jp):
            return self._send(404, {"error": "save the quote first"})
        with open(jp, encoding='utf-8') as f:
            data = json.load(f)
        if os.path.isfile(LOGO_PATH):
            data['_logo_path'] = LOGO_PATH
        base = slugify(data.get('cust_company') or data.get('cust_name') or 'quote')
        name = f"GCS_Quote_{base}"
        try:
            if fmt == "docx":
                out = os.path.join(jdir, name + ".docx")
                _gen_docx(data, out)
                return self._send_file(out,
                    "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
                    name + ".docx")
            else:
                out = os.path.join(jdir, name + ".pdf")
                _gen_pdf(data, out)
                return self._send_file(out, "application/pdf", name + ".pdf")
        except Exception as e:
            return self._send(500, {"error": str(e)})

    def _save_conveyor(self, data):
        jid = data.get('_id')
        if not jid or safe_job_dir(jid) is None:
            jid = new_conveyor_job_id(data)
        data['_id'] = jid
        data['_saved_at'] = datetime.now().isoformat(timespec='seconds')
        data['quote_type'] = 'conveyor'
        jdir = os.path.join(JOBS_DIR, jid)
        os.makedirs(jdir, exist_ok=True)
        with open(os.path.join(jdir, "conveyor.json"), 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=2)
        return self._send(200, {"ok": True, "id": jid})

    def _conveyor_extract(self, data):
        import firecrawl_extract
        urls = data.get('urls') or {}
        listing = (urls.get('listing') or '').strip()
        if not listing:
            return self._send(400, {"error": "listing URL is required"})
        request_quote = (urls.get('request_quote') or '').strip()
        custom_addons = bool(data.get('custom_addons_required'))
        quote_mode = data.get('quote_mode') or ('custom_build' if custom_addons else 'listing_only')
        pasted_addons = ""
        req_items = data.get('line_items') or []
        if req_items:
            pasted_addons = (req_items[0] or {}).get('addons') or ''
        if not custom_addons:
            request_quote = ""
        jid = data.get('job_id')
        jdir = safe_job_dir(jid) if jid else None
        if not jdir:
            jid = new_conveyor_job_id({"customer": data.get('customer') or {}})
            jdir = os.path.join(JOBS_DIR, jid)
            os.makedirs(jdir, exist_ok=True)
        try:
            result = firecrawl_extract.run_extraction(
                listing,
                request_quote or None,
                job_dir=jdir,
                force=bool(data.get('force')),
                custom_addons_required=custom_addons,
                quote_mode=quote_mode,
            )
            # Merge into existing conveyor.json if present
            jp = os.path.join(jdir, "conveyor.json")
            base = default_conveyor_quote()
            if os.path.isfile(jp):
                with open(jp, encoding='utf-8') as f:
                    base = json.load(f)
            base['urls'] = {"listing": listing, "request_quote": request_quote}
            base['quote_mode'] = result.get('quote_mode', quote_mode)
            base['custom_addons_required'] = result.get('custom_addons_required', custom_addons)
            base['_id'] = jid
            if custom_addons:
                import custom_build_parser
                existing_items = list(base.get('line_items') or [])
                existing_totals = dict(base.get('totals') or {})
                new_items = list(result.get('line_items') or [])
                if existing_items and new_items:
                    saved = existing_items[0] or {}
                    keep = {}
                    if str(saved.get('lead_time') or '').strip():
                        keep['lead_time'] = saved['lead_time']
                    if custom_build_parser._meaningful_custom_price(saved.get('amount')):
                        keep['amount'] = saved['amount']
                    new_items[0] = {**new_items[0], **keep}
                base['line_items'] = new_items or existing_items
                base['equipment_details'] = result.get('equipment_details') or base.get('equipment_details')
                merged_totals = dict(result.get('totals') or {})
                for key in ('subtotal', 'freight', 'tax', 'grand_total'):
                    val = existing_totals.get(key)
                    if key == 'subtotal':
                        if custom_build_parser._meaningful_custom_price(val):
                            merged_totals[key] = val
                    elif str(val or '').strip():
                        merged_totals[key] = val
                base['totals'] = merged_totals
            else:
                base['line_items'] = result.get('line_items') or base.get('line_items')
                base['equipment_details'] = result.get('equipment_details') or base.get('equipment_details')
                base['totals'] = result.get('totals') or base.get('totals')
            base['field_status'] = result.get('field_status') or {}
            if custom_addons and base.get('line_items'):
                base['line_items'][0]['addons'] = pasted_addons
                fs = dict(base.get('field_status') or {})
                fs['custom_addons'] = 'ok' if pasted_addons.strip() else 'missing'
                base['field_status'] = fs
            base['scrape_meta'] = result.get('scrape_meta') or {}
            base = refresh_conveyor_from_scrape(jdir, base)
            with open(jp, 'w', encoding='utf-8') as f:
                json.dump(base, f, indent=2)
            out = dict(base)
            out['field_status'] = base.get('field_status')
            return self._send(200, out)
        except Exception as e:
            return self._send(500, {"error": str(e)})

    def _conveyor_render(self, data):
        import conveyor_render
        jid = data.get('_id') or data.get('id')
        jdir = safe_job_dir(jid)
        if jdir is None:
            return self._send(400, {"error": "bad id"})
        jp = os.path.join(jdir, "conveyor.json")
        if not os.path.isfile(jp):
            return self._send(404, {"error": "save the quote first"})
        with open(jp, encoding='utf-8') as f:
            quote_data = json.load(f)
        # Allow inline updates from client before render
        for key in ('customer', 'rep', 'line_items', 'totals', 'equipment_details',
                    'quote_num', 'quote_date', 'urls', 'quote_mode', 'custom_addons_required'):
            if key in data:
                quote_data[key] = data[key]
        out_path = os.path.join(jdir, "GCS_Conveyor_Quote.html")
        try:
            conveyor_render.write_quote_html(quote_data, out_path)
            with open(jp, 'w', encoding='utf-8') as f:
                json.dump(quote_data, f, indent=2)
            return self._send(200, {"ok": True, "id": jid, "html_path": out_path})
        except Exception as e:
            return self._send(500, {"error": str(e)})

    def _conveyor_quote(self, jid):
        jdir = safe_job_dir(jid)
        if jdir is None:
            return self._send(400, {"error": "bad id"})
        html_path = os.path.join(jdir, "GCS_Conveyor_Quote.html")
        if os.path.isfile(html_path):
            with open(html_path, encoding='utf-8') as f:
                return self._send(200, f.read(), "text/html; charset=utf-8")
        jp = os.path.join(jdir, "conveyor.json")
        if not os.path.isfile(jp):
            return self._send(404, {"error": "not found"})
        import conveyor_render
        with open(jp, encoding='utf-8') as f:
            data = json.load(f)
        html_out = conveyor_render.render_quote_html(data)
        with open(html_path, 'w', encoding='utf-8') as f:
            f.write(html_out)
        return self._send(200, html_out, "text/html; charset=utf-8")

    def _conveyor_download(self, jid):
        jdir = safe_job_dir(jid)
        if jdir is None:
            return self._send(400, {"error": "bad id"})
