class ThreadingHTTPServer(ThreadingMixIn, HTTPServer):
    daemon_threads = True


def _bind():
    """Bind to the first free port from PORT_FALLBACKS. Returns (server, port)."""
    last_err = None
    for p in PORT_FALLBACKS:
        try:
            return ThreadingHTTPServer(("127.0.0.1", p), Handler), p
        except OSError as e:
            last_err = e
            continue
    raise SystemExit(
        "Could not start: all candidate ports are busy. "
        f"Close other copies of the app and try again. ({last_err})")


