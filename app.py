# A job id is generated by new_job_id() as "<YYYYMMDD>_<HHMMSS>__<slug>".
# Anything that doesn't match this exact shape is rejected to prevent a
# crafted id (e.g. containing "..") from escaping the jobs directory.
JOB_ID_RE = re.compile(r'^\d{8}_\d{6}__[A-Za-z0-9_]+$')

os.makedirs(JOBS_DIR, exist_ok=True)


def refresh_conveyor_from_scrape(jdir, data):
    """Always parse cached scrapes with the latest parser on disk."""
    import importlib

    data = data or {}
    if data.get("quote_mode") == "custom_build" or data.get("custom_addons_required"):
        import custom_build_parser
        importlib.reload(custom_build_parser)
        return custom_build_parser.refresh_quote_from_scrape(jdir, data)

    import listing_parser
    importlib.reload(listing_parser)
    return listing_parser.refresh_quote_from_scrape(jdir, data)


def safe_job_dir(jid):
    """Return the absolute path to a job folder, or None if jid is unsafe.

    Validates against the known id pattern AND confirms the resolved path
    stays inside JOBS_DIR, so traversal via symlinks or odd input can't
    read/delete files elsewhere on disk.
    """
    if not jid or not JOB_ID_RE.match(jid):
        return None
    jdir = os.path.realpath(os.path.join(JOBS_DIR, jid))
    root = os.path.realpath(JOBS_DIR)
    if jdir != root and not jdir.startswith(root + os.sep):
        return None
    return jdir

# Lazy imports so a missing lib gives a friendly message, not a crash on boot
def _gen_docx(data, path):
    import docgen
    return docgen.build_quote(data, path)

def _gen_pdf(data, path):
    import pdfgen
    return pdfgen.build_quote_pdf(data, path)


def slugify(s):
    s = re.sub(r'[^a-zA-Z0-9]+', '_', (s or '').strip())
    return re.sub(r'_+', '_', s).strip('_')[:40] or 'quote'


def new_job_id(data):
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    cust = slugify(data.get('cust_company') or data.get('cust_name') or 'quote')
    return f"{stamp}__{cust}"


def new_conveyor_job_id(data):
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    customer = data.get('customer') or {}
    cust = slugify(customer.get('company') or customer.get('contact') or 'conveyor')
    return f"{stamp}__{cust}"


def list_conveyor_jobs():
    out = []
    if not os.path.isdir(JOBS_DIR):
        return out
    for jid in os.listdir(JOBS_DIR):
        jp = os.path.join(JOBS_DIR, jid, "conveyor.json")
        if not os.path.isfile(jp):
            continue
        try:
            with open(jp, encoding='utf-8') as f:
                d = json.load(f)
            li = (d.get('line_items') or [{}])[0]
            out.append({
                "id": jid,
                "cust_company": (d.get('customer') or {}).get('company', ''),
                "quote_num": d.get('quote_num', ''),
                "saved_at": d.get('_saved_at', ''),
                "machine": li.get('model', ''),
                "total": _num((d.get('totals') or {}).get('grand_total')),
            })
        except Exception:
            continue
    out.sort(key=lambda x: x.get('saved_at', ''), reverse=True)
    return out


