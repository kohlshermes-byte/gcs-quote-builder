def list_jobs():
    out = []
    if not os.path.isdir(JOBS_DIR):
        return out
    for jid in os.listdir(JOBS_DIR):
        jpath = os.path.join(JOBS_DIR, jid, "quote.json")
        if os.path.isfile(jpath):
            try:
                with open(jpath, encoding='utf-8') as f:
                    d = json.load(f)
                eq = sum(_num(i.get('amount')) for i in d.get('equipment_items', []))
                fr = sum(_num(i.get('amount')) for i in d.get('freight_items', []))
                out.append({
                    "id": jid,
                    "cust_company": d.get('cust_company', ''),
                    "cust_name": d.get('cust_name', ''),
                    "date": d.get('date', ''),
                    "rep_name": d.get('rep_name', ''),
                    "total": eq + fr,
                    "saved_at": d.get('_saved_at', ''),
                    "machine": (d.get('equipment_items') or [{}])[0].get('desc', ''),
                })
            except Exception:
                continue
    out.sort(key=lambda x: x.get('saved_at', ''), reverse=True)
    return out


def _num(v):
    try:
        return float(str(v).replace("$", "").replace(",", "").strip() or 0)
    except (ValueError, TypeError):
        return 0.0


class Handler(BaseHTTPRequestHandler):
    def log_message(self, *a):
        pass  # quiet

